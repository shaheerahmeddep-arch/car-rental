#   DJANGO_EMAIL_BACKEND=django.core.mail.backends.smtp.EmailBackend
#   EMAIL_HOST_USER=your.gmail.address@gmail.com
#   EMAIL_HOST_PASSWORD=your-16-character-gmail-app-password
#
# Gmail requires an "App Password" (not your normal password) — generate one
# at https://myaccount.google.com/apppasswords after enabling 2-Step Verification.
